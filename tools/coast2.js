import { Vehicle } from '../src/physics/vehicle.js';
import { Simulation } from '../src/physics/sim.js';
import { flatWorld } from '../src/physics/terrain.js';
import { settleBlueprint } from '../src/physics/settle.js';
import { kestrelSpec } from '../src/vehicles/kestrel.js';
import { assemble } from '../src/vehicles/assemble.js';
const n = parseInt(process.argv[2] || '20'); const cd = parseFloat(process.argv[3] || '1.4');
const spec = structuredClone(kestrelSpec); spec.axle.front.tire.n = n; spec.axle.rear.tire.n = n;
const bp = assemble(spec); settleBlueprint(bp);
const world = flatWorld(3000, 4, 0);
const sim = new Simulation(world); const v = new Vehicle(bp); v.place(0,0,0,world,0); sim.add(v); v.keepAwake = true; v.contactDamp = cd;
for (let i = 0; i < 1000; i++) sim.step();
v.drive.gear = 0; v.drive.dir = 'N';
const V0 = 80/3.6; for (let i = 0; i < v.nc; i++) v.vel[3*i+2] = -V0;
for (let i = 0; i < 4000; i++) sim.step();
v.frameUpdate(0.1); const s0 = v.frame.speed;
for (let i = 0; i < 6000; i++) sim.step();
v.frameUpdate(0.1);
console.log(`n=${n} contactDamp=${cd}: decel ${((s0 - v.frame.speed)/3).toFixed(3)} m/s2 at ~${(s0*3.6).toFixed(0)}->${(v.frame.speed*3.6).toFixed(0)} km/h`);
